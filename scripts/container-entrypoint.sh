#!/usr/bin/env bash

set -euo pipefail

# Set default value for positional parameters to avoid unbound variable errors
# Main: everything below runs only when the script is EXECUTED (not
# sourced by tests). Unit tests source this file to reach the
# functions above directly.
main() {
  if [ $# -eq 0 ]; then
    set -- "bash" "-c" "while true; do sleep 3600; done"
  fi

  metrics_enabled="${OPENCODE_METRICS_ENABLED:-1}"
  metrics_host="${OPENCODE_METRICS_HOST:-0.0.0.0}"
  metrics_port="${OPENCODE_METRICS_PORT:-9464}"
  metrics_dir="${OPENCODE_RUN_METRICS_DIR:-/app/share/opencode-runs}"

  # Fail fast with a clear message when the workspace is not writable by the
  # container user. Most common cause: image built with a different APP_UID
  # than the host user that owns the workspace bind mount (build with
  # HOST_UID=$(id -u) HOST_GID=$(id -g), or use `make up`).
  if [ ! -w /workspace ]; then
    echo "ERROR: /workspace is not writable by $(id -u):$(id -g)." >&2
    echo "       The image was likely built with a different APP_UID than the" >&2
    echo "       owner of the workspace bind mount." >&2
    echo "       Rebuild with: HOST_UID=\$(id -u) HOST_GID=\$(id -g) docker compose build" >&2
    echo "       or just use: make up" >&2
    exit 1
  fi

  # Map opencode configuration to goose at startup
  if [ -f "/home/appuser/.config/goose/setup-goose-env.sh" ]; then
    source "/home/appuser/.config/goose/setup-goose-env.sh"
  fi

  # Shared LLM endpoint env (generated by sync-llm-config.sh): make the
  # goose litellm provider vars visible to goose sessions and shells.
  if [ -f "/home/appuser/.config/goose/set-env.sh" ]; then
    set +u; source "/home/appuser/.config/goose/set-env.sh"; set -u
  fi

  # GPG support: reuse host keys inside the container.
  #
  # A host GNUPGHOME mount carries the host's daemon state, which is dead
  # inside the container/VM: unix sockets do not survive bind mounts (and
  # on Docker Desktop for Mac/VirtioFS they appear as plain files). That
  # makes gpg fail with "can't connect to keyboxd" or hang on stale locks.
  # Two ways to reuse keys (see README "Use your GPG keys"):
  #   1. MOUNT the host ~/.gnupg (compose: GPG_HOME_DIR mount): the
  #      entrypoint cleans dead sockets/locks so container daemons start.
  #   2. IMPORT a key (GPG_IMPORT_FILE, e.g. an armored secret-key
  #      export): keys land in the container-local GNUPGHOME - no daemon
  #      state shared with the host, works on every platform.
  gnupg_home="${GNUPGHOME:-$HOME/.gnupg}"


  if [ -n "${GPG_IMPORT_FILE:-}" ] && [ "${GPG_IMPORT_FILE}" != "/dev/null" ] && [ ! -e "$GPG_IMPORT_FILE" ]; then
    # set but not mounted: point the user at the missing volume mount
    echo "WARNING: GPG_IMPORT_FILE is set to '$GPG_IMPORT_FILE' but the file does not exist in the container." >&2
    echo "         Mount the key export as a volume (see README 'Use your GPG keys')." >&2
  fi

  if [ -n "${GPG_IMPORT_FILE:-}" ] && [ -s "$GPG_IMPORT_FILE" ]; then
    # Import mode: bring keys into the container-local GNUPGHOME.
    # Idempotent: gpg de-duplicates on re-import, so this runs on every
    # start and keeps the (now volume-persisted) keyring in sync.
    mkdir -p "$gnupg_home"
    chmod 700 "$gnupg_home"
    if gpg --batch --import "$GPG_IMPORT_FILE" 2>/dev/null; then
      echo "gpg: imported keys from $GPG_IMPORT_FILE"
      # optionally trust imported public keys ultimately (ownertrust level 6)
      if [ "${GPG_TRUST_IMPORTED:-0}" = "1" ]; then
        for fpr in $(gpg --list-keys --with-colons 2>/dev/null | awk -F: '/^fpr:/ {print $10}'); do
          echo "$fpr:6:" | gpg --import-ownertrust 2>/dev/null || true
        done
      fi
    else
      echo "WARNING: gpg import from $GPG_IMPORT_FILE failed" >&2
    fi

    # If exactly ONE secret key is available, wire it into git signing so
    # `git commit -S` / `git tag -s` work out of the box. With multiple
    # keys we do not guess - set user.signingkey yourself.
    if [ -z "$(git config --global user.signingkey 2>/dev/null || true)" ]; then
      primary_fpr="$(gpg --list-secret-keys --with-colons 2>/dev/null \
        | awk -F: '/^fpr:/ {print $10; exit}')"
      secret_count="$(gpg --list-secret-keys --with-colons 2>/dev/null \
        | awk -F: '/^sec:/ {c++} END {print c+0}')"
      if [ -n "$primary_fpr" ] && [ "$secret_count" -eq 1 ]; then
        git config --global user.signingkey "$primary_fpr"
        git config --global commit.gpgsign true
        git config --global tag.gpgsign true
        echo "gpg: git signing configured (user.signingkey=$primary_fpr, commit.gpgsign=true)"
      fi
    fi
  else
    # Mount mode: clean dead daemon state so container-side daemons start
    gpg_clean_dead_daemon_state "$gnupg_home"
  fi

  # Export the LLM API key into the container environment (PID 1 context,
  # inherited by every opencode/goose process and shell). Resolution order:
  # 1. env var already set (compose environment) - keep it
  # 2. docker compose secret /run/secrets/llm_api_key (e.g. from `pass` via
  #    make up) - read first line, trim whitespace
  # The generated agent configs only REFERENCE the env var ({env:...} /
  # ${...}), so it must actually be present in the process environment.
  llm_key_env="${LLM_API_KEY_ENV:-CUSTOM_LITELLM_API_KEY}"
  # 2>/dev/null: on Docker Desktop for Mac the secret path can be a broken
  # symlink after `make up` removed its temp source file - never print noise
  if [ -z "${!llm_key_env:-}" ] && [ -s /run/secrets/llm_api_key ] 2>/dev/null; then
    key_value="$(head -n1 /run/secrets/llm_api_key 2>/dev/null | tr -d '[:space:]')"
    if [ -n "$key_value" ]; then
      export "$llm_key_env"="$key_value"
      echo "Loaded ${llm_key_env} from /run/secrets/llm_api_key"
    fi
  fi

  # Auto-detect if we should use goose-opencode wrapper
  if [ -f "/usr/local/bin/goose-opencode" ] && [ "$1" = "opencode" ]; then
    echo "🔄 Mapping opencode configuration to goose..."
    set -- goose-opencode "${@:2}"
  fi

  # Goosetown: all goosetown env points at a cloned goosetown repository
  # inside the workspace (host-visible via the workspace bind mount). The clone
  # happens on first start; to use your own goosetown fork, place a clone at
  # $GOOSETOWN_DIR (default /workspace/goosetown) or point GOOSETOWN_DIR at it.
  goosetown_dir="${GOOSETOWN_DIR:-/workspace/goosetown}"
  if [ ! -e "$goosetown_dir" ]; then
    goosetown_url="${GOOSETOWN_REPO_URL:-https://github.com/aaif-goose/goosetown.git}"
    clone_args=()
    if [ -n "${GOOSETOWN_REF:-}" ]; then
      clone_args+=(--branch "$GOOSETOWN_REF")
    fi
    echo "Cloning goosetown from ${goosetown_url} into ${goosetown_dir} ..."
    if git clone "${clone_args[@]+"${clone_args[@]}"}" "$goosetown_url" "$goosetown_dir"; then
      echo "goosetown cloned. Working dirs (GUIDES/PLANS/RESEARCH/WORK_LOGS) live inside it."
    else
      echo "WARNING: could not clone goosetown; goose/goosetown orchestrator may not work" >&2
    fi
  fi
  export GOOSETOWN_DIR="$goosetown_dir"
  export GUIDES_DIR="$goosetown_dir/GUIDES"
  export PLANS_DIR="$goosetown_dir/PLANS"
  export RESEARCH_DIR="$goosetown_dir/RESEARCH"
  export WORK_LOGS_DIR="$goosetown_dir/WORK_LOGS"

  # Persist to .bashrc so interactive shells (docker compose exec) see the
  # same locations; these shells do not inherit PID 1's exports.
  if [ -f "/home/appuser/.bashrc" ] && ! grep -q "GOOSETOWN_DIR=" /home/appuser/.bashrc 2>/dev/null; then
    cat >> /home/appuser/.bashrc <<'BASHRC_EOF'

# Goosetown working repository (cloned into the workspace)
export GOOSETOWN_DIR="$goosetown_dir"
export GUIDES_DIR="$goosetown_dir/GUIDES"
export PLANS_DIR="$goosetown_dir/PLANS"
export RESEARCH_DIR="$goosetown_dir/RESEARCH"
export WORK_LOGS_DIR="$goosetown_dir/WORK_LOGS"
BASHRC_EOF
  fi

  # Use goose wrapper from the workspace goosetown clone (telepathy + wall);
  # fall back to the copy baked into the image at /app/goosetown.
  if [ "$1" = "goose" ]; then
    GOOSE_WRAPPER="${GOOSETOWN_DIR}/goose"
    if [ ! -f "$GOOSE_WRAPPER" ]; then
      GOOSE_WRAPPER="/app/goosetown/goose"
    fi
    if [ -f "$GOOSE_WRAPPER" ]; then
      echo "🦆 goosetown telepathy enabled - using $GOOSE_WRAPPER"
      set -- "$GOOSE_WRAPPER" "${@:2}"
    fi
  fi

  if [[ "$metrics_enabled" != "0" ]]; then
    python3 /app/scripts/opencode-prometheus-exporter.py \
      --host "$metrics_host" \
      --port "$metrics_port" \
      --metrics-dir "$metrics_dir" &
  fi

  # Register the example remote MCP server (https://jarakube.eu/mcp) with
  # both agents on first start. Opt out with MCP_EXAMPLE_ENABLED=0; override
  # name/url with MCP_EXAMPLE_NAME / MCP_EXAMPLE_URL.
  if [ "${MCP_EXAMPLE_ENABLED:-1}" != "0" ]; then
    mcp_name="${MCP_EXAMPLE_NAME:-jarakube-website}"
    mcp_url="${MCP_EXAMPLE_URL:-https://jarakube.eu/mcp}"

    # OpenCode: only add if not already configured (idempotent)
    if command -v opencode >/dev/null 2>&1 \
       && ! opencode mcp list 2>/dev/null | grep -q "^${mcp_name}\|${mcp_name}"; then
      if opencode mcp add "$mcp_name" --url "$mcp_url" >/dev/null 2>&1; then
        echo "Registered example MCP server '${mcp_name}' ($mcp_url) with opencode"
      fi
    fi

    # Goose: merge into ~/.config/goose/config.yaml if not present
    goose_config="/home/appuser/.config/goose/config.yaml"
    if [ ! -f "$goose_config" ] || ! grep -q "^[[:space:]]*${mcp_name}:" "$goose_config"; then
      mkdir -p /home/appuser/.config/goose
      touch "$goose_config"
      if [ -s "$goose_config" ] && ! grep -q "^mcp_servers:" "$goose_config"; then
        printf '\nmcp_servers:\n' >> "$goose_config"
      elif [ ! -s "$goose_config" ]; then
        printf 'mcp_servers:\n' >> "$goose_config"
      fi
      printf '  %s:\n    url: %s\n' "$mcp_name" "$mcp_url" >> "$goose_config"
      echo "Registered example MCP server '${mcp_name}' ($mcp_url) with goose"
    fi
  fi

  # Keep OpenCode and goose LLM configuration in sync from the shared
  # LLM_* environment variables (single source of truth). No-op when
  # LLM_ENDPOINT is unset.
  if [ -x /app/scripts/sync-llm-config.sh ]; then
    /app/scripts/sync-llm-config.sh || echo "WARNING: LLM config sync failed" >&2
  fi

  # Add Goosetown aliases to bashrc for persistence
  if [ -f "/home/appuser/.bashrc" ] && ! grep -q "goosetown" /home/appuser/.bashrc 2>/dev/null; then
    echo '' >> /home/appuser/.bashrc
    echo '# Goosetown alias - automatically loads goosetown orchestrator' >> /home/appuser/.bashrc
    echo 'alias goosetown="goose load source:goosetown-orchestrator"' >> /home/appuser/.bashrc
    echo 'alias gt="goose load source:goosetown-orchestrator"' >> /home/appuser/.bashrc
  fi

  # Source bashrc to set variables in current shell
  if [ -f "/home/appuser/.bashrc" ]; then
    source /home/appuser/.bashrc
  fi

  # Hand over to the container command (PID 1 becomes the CMD)
  exec "$@"
}

gpg_clean_dead_daemon_state() {
  # $1 = gnupg home
  local home="$1"
  [ -d "$home" ] || return 0
  # Daemon sockets that are dead artifacts: a real socket whose
  # connect() fails, or a socket degraded into a regular file
  # (macOS VM mounts turn host sockets into plain files).
  local sock
  for sock in "$home"/S.keyboxd "$home"/S.gpg-agent "$home"/S.gpg-agent.browser \
               "$home"/S.gpg-agent.extra "$home"/S.gpg-agent.ssh; do
    [ -e "$sock" ] || continue
    if [ -S "$sock" ]; then
      if ! python3 -c "import socket; s = socket.socket(socket.AF_UNIX); s.connect('$sock')" 2>/dev/null; then
        echo "gpg: stale daemon socket $sock (mounted from host?) - removing"
        rm -f "$sock"
      fi
    else
      echo "gpg: dead socket artifact $sock - removing"
      rm -f "$sock"
    fi
  done
  # Stale cross-machine lock files: gnupg locks record the holder's pid
  # and hostname; a lock taken on the host never resolves in the container.
  local lock
  while IFS= read -r lock; do
    echo "gpg: stale lock file $lock (from host?) - removing"
    rm -f "$lock"
  done < <(find "$home" -maxdepth 2 -name '*.lock' -type f 2>/dev/null)
}

# Source guard: bats unit tests source this file; running it starts the
# container. Only execute when run directly.
if [ "${BASH_SOURCE[0]}" = "$0" ]; then
  main "$@"
fi
